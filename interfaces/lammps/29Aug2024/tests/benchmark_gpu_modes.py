#!/usr/bin/env python3
"""Compare GPU direct/moment/auto, checking forces, energy and virial.

Use a CPU in.test generated by check_gpu.py. Each independent sample has a
warmup, a timed NVE run, then an untimed force/atom-energy snapshot. Modes rotate
between samples to reduce order bias. NumPy is required for numerical checks.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import statistics
import subprocess
import sys

import numpy as np


def snapshot(path):
    lines = path.read_text().splitlines()
    start = next(i for i, line in enumerate(lines) if line.startswith('ITEM: ATOMS')) + 1
    return np.array([list(map(float, line.split())) for line in lines[start:]])


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--lammps', type=Path, required=True)
    p.add_argument('--input', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--replicates', nargs='+', type=int, default=[1, 2, 6, 10])
    p.add_argument('--samples', type=int, default=3)
    p.add_argument('--steps', type=int, default=100)
    p.add_argument('--warmup', type=int, default=20)
    p.add_argument('--cpu', type=int, default=6)
    a = p.parse_args()
    if min(a.samples, a.steps, a.warmup, *a.replicates) < 1:
        p.error('counts must be positive')
    a.output = a.output.resolve()
    a.output.mkdir(parents=True, exist_ok=True)
    base = a.input.read_text().split('run 0')[0]
    if 'pair_style accelnet ' not in base or 'package gpu' in base:
        p.error('--input must be a CPU input from check_gpu.py')
    base = re.sub(r'^thermo \d+$', f'thermo {a.steps}', base, flags=re.M)
    base = re.sub(r'^neigh_modify .*$', 'neigh_modify every 10 delay 0 check yes', base, flags=re.M)
    base = re.sub(r'^atom_modify .*$', 'atom_modify sort 100 0.0', base, flags=re.M)
    base = '\n'.join(line for line in base.splitlines() if not line.startswith('compute ea'))
    base = base.replace('clear', 'clear\npackage gpu 1 neigh yes newton on split 1', 1)
    provenance = dict(command=sys.argv, executable=str(a.lammps.resolve()),
                      executable_sha256=hashlib.sha256(a.lammps.read_bytes()).hexdigest(),
                      cuda_visible_devices=os.environ.get('CUDA_VISIBLE_DEVICES'),
                      warmup=a.warmup, steps=a.steps, samples=a.samples,
                      script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                      input=str(a.input.resolve()))
    report = dict(provenance=provenance, results=[])
    for rep in a.replicates:
        runs = {mode: [] for mode in ['direct', 'moment', 'auto']}
        reference_dump = reference_thermo = None
        for sample in range(a.samples):
            modes = ['direct', 'moment', 'auto']
            modes = modes[sample % 3:] + modes[:sample % 3]
            for mode in modes:
                directory = a.output / f'{24*rep**3}-{mode}-{sample}'
                directory.mkdir(exist_ok=True)
                text = re.sub(r'replicate \d+ \d+ \d+', f'replicate {rep} {rep} {rep}', base)
                text = re.sub(r'pair_style accelnet \w+ ', f'pair_style accelnet/gpu {mode} ', text)
                text += f'\nrun {a.warmup}\nrun {a.steps}\n'
                # Dump/pe-atom evaluation is outside the timed run.
                text += ('compute ea all pe/atom\nrun 0\n'
                         'write_dump all custom final.dump id type x y z fx fy fz c_ea '
                         'modify sort id format float %.17g\n')
                (directory / 'in.benchmark').write_text(text)
                env = dict(os.environ, OMP_NUM_THREADS='1', OPENBLAS_NUM_THREADS='1',
                           OMP_TARGET_OFFLOAD='MANDATORY')
                command = ['taskset', '-c', str(a.cpu), str(a.lammps.resolve()), '-in', 'in.benchmark']
                with (directory / 'stdout.txt').open('w') as f:
                    subprocess.run(command, cwd=directory, env=env, stdout=f,
                                   stderr=subprocess.STDOUT, timeout=600, check=True)
                log = (directory / 'stdout.txt').read_text()
                loops = re.findall(r'Loop time of ([\d.eE+-]+)', log)
                pairs = re.findall(r'^Pair\s+\|\s*([\d.eE+-]+)\s*\|\s*([\d.eE+-]+)', log, re.M)
                if len(loops) != 3 or len(pairs) != 3:
                    raise RuntimeError(f'Unexpected timing output in {directory}')
                thermo = []
                for line in log.splitlines():
                    fields = line.split()
                    if len(fields) == 8 and re.fullmatch(r'\d+', fields[0]):
                        try:
                            thermo.append(list(map(float, fields)))
                        except ValueError:
                            pass
                thermo = np.array(thermo)
                got = snapshot(directory / 'final.dump')
                if not np.isfinite(thermo).all() or not np.isfinite(got).all():
                    raise RuntimeError(f'Nonfinite results in {directory}')
                if reference_dump is None:
                    reference_dump, reference_thermo = got, thermo
                np.testing.assert_allclose(got[:, :2], reference_dump[:, :2], atol=0, rtol=0)
                np.testing.assert_allclose(got[:, 2:], reference_dump[:, 2:], atol=2e-8, rtol=2e-9)
                np.testing.assert_allclose(thermo, reference_thermo, atol=2e-5, rtol=2e-9)
                item = dict(sample=sample, seconds_per_step=float(loops[1])/a.steps,
                            pair_seconds_per_step=float(pairs[1][1])/a.steps,
                            max_force_error=float(np.max(np.abs(got[:, 5:8]-reference_dump[:, 5:8]))),
                            max_atom_energy_error=float(np.max(np.abs(got[:, 8]-reference_dump[:, 8]))),
                            max_total_energy_error=float(np.max(np.abs(thermo[:, 1]-reference_thermo[:, 1]))),
                            max_pressure_error=float(np.max(np.abs(thermo[:, 2:]-reference_thermo[:, 2:]))))
                runs[mode].append(item)
                print(json.dumps(dict(atoms=len(got), mode=mode, **item)), flush=True)
        for mode, samples in runs.items():
            report['results'].append(dict(atoms=24*rep**3, mode=mode, samples=samples,
                seconds_per_step=statistics.median(x['seconds_per_step'] for x in samples),
                pair_seconds_per_step=statistics.median(x['pair_seconds_per_step'] for x in samples)))
        (a.output / 'report.json').write_text(json.dumps(report, indent=2)+'\n')


if __name__ == '__main__':
    main()
